"""Pack a subset of MNIST into web/mnist-data.js for the interactive page.

The page is opened straight from disk (file://), where browsers block fetch(),
so the data ships as a JavaScript file holding a base64 string. The payload is
gzip-compressed and decompressed in the browser with DecompressionStream.

Binary layout (little-endian), before gzip:
    uint32 n_train, uint32 n_test,
    n_train*784 uint8 train pixels, n_train uint8 train labels,
    n_test*784  uint8 test pixels,  n_test  uint8 test labels

Usage:
    python export_web_data.py                 # 10,000 train / 2,000 test
    python export_web_data.py --train 20000
"""

import argparse
import base64
import gzip
import struct
from pathlib import Path

import numpy as np

from mnist_digits.data import DEFAULT_DATA_DIR, _read_idx, load_mnist


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--train", type=int, default=10000, help="training images to include")
    parser.add_argument("--test", type=int, default=2000, help="test images to include")
    parser.add_argument("--data-dir", type=Path, default=DEFAULT_DATA_DIR)
    parser.add_argument("--out", type=Path, default=Path("web/mnist-data.js"))
    parser.add_argument("--seed", type=int, default=0)
    args = parser.parse_args()

    load_mnist(args.data_dir)  # downloads the raw files if they're missing
    d = args.data_dir
    x_train = _read_idx(d / "train-images-idx3-ubyte.gz")
    y_train = _read_idx(d / "train-labels-idx1-ubyte.gz")
    x_test = _read_idx(d / "t10k-images-idx3-ubyte.gz")
    y_test = _read_idx(d / "t10k-labels-idx1-ubyte.gz")

    # Random subsets so every digit is represented and training order is mixed.
    rng = np.random.default_rng(args.seed)
    tr = rng.permutation(len(x_train))[:args.train]
    te = rng.permutation(len(x_test))[:args.test]

    payload = b"".join([
        struct.pack("<II", len(tr), len(te)),
        x_train[tr].tobytes(), y_train[tr].astype(np.uint8).tobytes(),
        x_test[te].tobytes(), y_test[te].astype(np.uint8).tobytes(),
    ])
    packed = base64.b64encode(gzip.compress(payload, compresslevel=9)).decode("ascii")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "// Generated by export_web_data.py - MNIST subset, gzip + base64.\n"
        f"window.MNIST_DATA = {{ nTrain: {len(tr)}, nTest: {len(te)}, gzipBase64: \"{packed}\" }};\n",
        encoding="ascii",
    )
    counts = np.bincount(y_train[tr], minlength=10)
    print(f"Wrote {args.out} ({args.out.stat().st_size / 1e6:.1f} MB): "
          f"{len(tr)} train / {len(te)} test; train images per digit {counts.tolist()}")


if __name__ == "__main__":
    main()
